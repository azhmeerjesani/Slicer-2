    def _preloadScientificModules(self):
        """Import scipy.stats (about 2 s) in a background thread on the first visit, so that resolving the
        first threshold rule never freezes the application.

        Python threads only run while the main thread runs Python, so a 15 ms timer lends them the
        interpreter until the import is done.
        """
        if "scipy.stats" in sys.modules or self._preloading:
            return
        import threading

        self._preloading = True
        finished = threading.Event()

        def work():
            try:
                import scipy.stats  # noqa: F401
            except Exception:
                logging.exception("Lesion network mapping: scipy.stats could not be imported")
            finished.set()

        def pump():
            if finished.is_set():
                self._pumpTimer.stop()
                self._preloading = False
                self.refreshResult(reloadMaps=False)
                return
            time.sleep(0.003)  # releases the interpreter to the import thread

        self._pumpTimer = qt.QTimer()
        self._pumpTimer.setInterval(15)
        self._pumpTimer.connect("timeout()", pump)
        threading.Thread(target=work, name="lnm-preload", daemon=True).start()
        self._pumpTimer.start()

    def _syncStudy(self):
        """The open study: the Studio study session's, else the parameter node's studyPath (None without one)."""
        shell = self._shell()
        session = getattr(shell, "studySession", None) if shell is not None else None
        study = getattr(session, "study", None) if session is not None else None
        node = self._parameterNode
        if study is None and node is not None and node.studyPath and os.path.isfile(os.path.join(node.studyPath, "study.json")):
            try:
                from LesionNetworkMappingLib.study import Study

                study = self.ctx.study if getattr(self.ctx.study, "path", None) == node.studyPath else Study.open(node.studyPath)
            except Exception:
                logging.exception("Lesion network mapping: the study could not be opened")
                study = None
        if study is not self.ctx.study:
            self.ctx.setStudy(study)
            self._notifyControllers("onStudyChanged")

    def exit(self):
        self._entered = False
        shell = self._shell()
        if shell is not None:
            try:
                if self._footerInShell and shell.inspectorFooter() is self.shellFooter:
                    shell.setInspectorFooter(None)
                if getattr(shell, "_primaryAction", None) == self.onPrimary:
                    shell.setPrimaryAction(None, "")
                chip = getattr(getattr(shell, "topBar", None), "statusChip", None)
                from LesionNetworkMappingUI import jobrunner

                if self._statusChipText and chip is not None and str(chip.text) == self._statusChipText and not jobrunner.instance().ownsStatusChip():
                    shell.setStatusChip(None)
            except Exception:
                logging.exception("Lesion network mapping: leaving Map failed")
        self._footerInShell = False
        self._statusChipText = None
        self.footer.show()
        if self._outlineState is not None:
            from LesionNetworkMappingLib import display

            display.restoreLesionDisplay(self._outlineState)
            self._outlineState = None

