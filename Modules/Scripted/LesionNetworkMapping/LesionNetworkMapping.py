    def onRunEvent(self, event):
        kind = event.get("event")
        if kind == "progress":
            # Shown at most every 100 ms: an engine reports every subject
            self._pendingProgress = event
            if not self.progressTimer.isActive():
                self.progressTimer.start()
            return
        if kind == "start":
            names = event.get("lesions") or []
            if names:
                self.lesionName = names[0]
            self.progress.update()
        elif kind == "snapshot":
            self.runN = int(event.get("n") or 0)
            self.runPartial = True
            self.runOutputs = self._outputsByKey(event.get("outputs") or [])
            self.scheduleRefresh(reloadMaps=True)
        elif kind == "done":
            self.runN = int(event.get("n") or 0)
            self.runPartial = False
            self.runOutputs = self._outputsByKey(event.get("outputs") or [])
        elif kind == "queued":
            self.progress.update()
        self._notifyControllers("onRunEvent", event)

    def _showPendingProgress(self):
        from LesionNetworkMappingUI import jobrunner

        event, self._pendingProgress = self._pendingProgress, None
        if event is None or self.job is None or not self.job.isRunning():
            return
        done, total = event.get("done"), event.get("total")
        eta = jobrunner.formatEta(event.get("eta"))
        text = _("{done:,} / {total:,} subjects").format(done=int(done or 0), total=int(total or 0)) + (f" · ~{eta}" if eta else "")
        self.progress.setProgress((done or 0) / total if total else None, text)

    def _outputsByKey(self, outputs):
        """{"T", "AvgFz", "AvgR": path} of the run's lesion from an event's output list."""
        if self.bundle is None or not self.lesionName:
            return {}
        expected = self.logic.mapPaths(self.runDir, self.lesionName, self.bundle.name, self.runDescSuffix)
        normalized = {os.path.normpath(path) for path in outputs}
        return {key: path for key, path in expected.items() if os.path.normpath(path) in normalized}

    def onRunDone(self, job):
        from LesionNetworkMappingUI import context as contextModule, jobrunner

        self.progress.update()
        runJson = {}
        try:
            with open(os.path.join(self.runDir, "run.json"), encoding="utf-8") as f:
                runJson = json.load(f)
        except (OSError, ValueError, TypeError):
            pass
        self.progressTimer.stop()
        self._pendingProgress = None
        if job.state == "done" and not self.runOutputs:
            self.runOutputs = self._outputsByKey(job.outputs)
        if not self.runOutputs:
            # Stopped before the first partial map, or failed without one: the previous result comes back
            self._restorePreviousRun()
            if job.state != "cancelled":
                self._showRunFailure(job)
            qt.QTimer.singleShot(jobrunner.FINISHED_CHIP_MS + 200, self._refreshStatusChip)
            self.updateComputeState()
            self._notifyControllers("onRunDone", job)
            return
        self._previousRun = None
        if job.state == "done":
            self.runPartial = False
            self.scheduleRefresh(reloadMaps=True)
        elif job.state == "cancelled":
            # Stop keeps the latest snapshot, labelled "N=<n> (partial)"
            self.runPartial = True
            self.scheduleRefresh(reloadMaps=True)
        else:
            # Failed after a partial map: like Stop, the latest snapshot is kept, labelled "N=<n> (partial)"
            self.runPartial = True
            self.scheduleRefresh(reloadMaps=True)
            self._showRunFailure(job)
        # The job runner shows "Done" for a few seconds; Map's own chip ("Done · N=1000") follows
        qt.QTimer.singleShot(jobrunner.FINISHED_CHIP_MS + 200, self._refreshStatusChip)
        if self.runOutputs:
            run = contextModule.RunInfo(self.runDir, runJson, list(self.runOutputs.values()), self.runN, self.currentStatistic(), job, self.runPartial)
            self.ctx.setCurrentRun(run)
        self.updateComputeState()
        self._notifyControllers("onRunDone", job)

    def _showRunFailure(self, job):
        reason = job.failureReason or _("unknown error")
        self.widgets.setBannerText(self.computeBanner, _("Run failed: {reason}").format(reason=reason) + (f"\n{_('Log')}: {job.logPath}" if job.logPath else ""))
        self.computeBanner.show()

    def _restorePreviousRun(self):
        """Undo ``compute()`` for a run that ended without a map: remove its temporary volume and show the
        previous result again, as it was (name, saved with the scene, its rule and colour table alphas).
        """
        previous, self._previousRun = self._previousRun, None
        node = self._parameterNode
        temporary = node.resultVolume if node is not None else None
        if temporary is not None and temporary.GetScene() is not None and temporary.GetAttribute(COMPUTING_ATTRIBUTE) == "1":
            scene = temporary.GetScene()
            for index in reversed(range(temporary.GetNumberOfDisplayNodes())):
                if temporary.GetNthDisplayNode(index) is not None:
                    scene.RemoveNode(temporary.GetNthDisplayNode(index))
            if temporary.GetStorageNode() is not None:
                scene.RemoveNode(temporary.GetStorageNode())
            scene.RemoveNode(temporary)
        volume = previous["volume"] if previous is not None else None
        if volume is not None and volume.GetScene() is None:
            volume = None  # removed during the run
        if volume is not None:
            (self.lesionName, self.runDir, self.runOutputs, self.runN, self.runPartial, self.runPreviewN, self.runDescSuffix) = previous["state"]
            self._mapStamp.clear()
            self._mapStamp.update(previous["mapStamp"])
            run, ctxVolume = previous["run"], previous["ctxVolume"]
        else:
            self.runOutputs, self.runN, self.runPartial, self.runPreviewN, self.runDescSuffix = {}, None, False, None, ""
            self._mapStamp.clear()
            run, ctxVolume = None, None
        self._valuesCache.clear()
        if node is not None:
            node.resultVolume = volume
        self.ctx.setResultVolume(ctxVolume if ctxVolume is None or ctxVolume.GetScene() is not None else None)
        self.ctx.setCurrentRun(run)
        if volume is not None:
            self._showLayers(volume)
        self.refreshResult()

    def stop(self):
        """Stop the running computation (the Stop button; never Esc)."""
        if self.job is not None:
            self.job.stop()

