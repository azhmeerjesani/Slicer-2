"""Lesion Network Mapping: the Map workspace of Slicer Studio, also a regular module in Classic (SPEC 7).

From a traced lesion (a segment) and a registered normative connectome bundle, the module computes the
lesion's network maps (mean r, mean Fisher z and T over the connectome subjects) in a subprocess, shows
them with the "LNM Diverging" colour table and threshold rules, and exports them with sidecars and
provenance. The cards are built in code; cards added by later work packages are plug-ins discovered in
``LesionNetworkMappingUI`` (``card_*.py``).

Run as a module (``PythonSlicer -m LesionNetworkMapping job <module> [arguments]``) this file is the job
entry point of the GUI job runner for library command lines that do not read ``--cancel-file`` yet: it
removes ``--cancel-file F`` from the arguments, turns the appearance of that file into a cancellation
request (as SIGTERM does) and runs ``<module>.main`` with the job protocol (``jobs.run_job``).
``PythonSlicer -m LesionNetworkMapping demo --out DIR`` writes the synthetic demo connectome as a job ("Use the
demo"), so that its ~60 MB are written outside the application's main thread, with progress.
"""

import sys

#: The synthetic demo connectome (written on request into <cache>/LNM/demo.lnmc)
DEMO_NAME = "Synthetic demo"
DEMO_LABEL = "SYNTHETIC — not real data"
DEMO_TERMS = ("SYNTHETIC — not real data. This connectome was generated by Slicer Studio from random numbers with planted networks, "
              "for trying the Map workspace and for tests. It describes no person; its maps mean nothing about the brain. "
              "There are no restrictions on its use.")
DEMO_SUBJECTS = 120
#: Grid of the demo: 6 mm voxels over the MNI brain (centre (0, -18, 8) mm), so that a lesion traced on the
#: MNI template can be mapped with it; about 60 MB on disk
DEMO_SHAPE = (24, 28, 24)
DEMO_SPACING_MM = 6.0
DEMO_CENTER_MM = (0.0, -18.0, 8.0)
#: Template space recorded in the demo's connectome.json ("space"): its grid is not a standard one, so the
#: native-space check (M6) knows from this that it is an MNI connectome
DEMO_SPACE = "MNI152NLin2009cAsym"
#: Runs of each subject of the demo (time points)
DEMO_RUNS = (20, 20)


def writeDemoConnectome(path, nSubjects=DEMO_SUBJECTS, shape=DEMO_SHAPE, runs=DEMO_RUNS, seed=0, affine="demo", onSubject=None):
    """Write the synthetic demo connectome (``connectome.make_synthetic`` and its SYNTHETIC metadata) to ``path``.

    Needs numpy only (no application): it runs in the GUI for small test bundles and in the demo job.
    ``onSubject(done, total)`` is called after each subject is written; it may raise to stop.
    Returns the ``make_synthetic`` result (path, blobs...).
    """
    import os

    import numpy as np

    from LesionNetworkMappingLib import connectome

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    space = None
    if isinstance(affine, str) and affine == "demo":
        affine = np.diag([DEMO_SPACING_MM, DEMO_SPACING_MM, DEMO_SPACING_MM, 1.0])
        affine[:3, 3] = np.asarray(DEMO_CENTER_MM) - (np.asarray(shape) - 1) / 2.0 * DEMO_SPACING_MM
        space = DEMO_SPACE  # positioned on the MNI brain: lesions must be in MNI space too
    writerClass = connectome.ConnectomeWriter
    originalAddSubject = writerClass.add_subject
    if onSubject is not None:
        written = [0]

        def addSubject(writer, *args, **kwargs):
            result = originalAddSubject(writer, *args, **kwargs)
            written[0] += 1
            onSubject(written[0], int(nSubjects))
            return result

        writerClass.add_subject = addSubject
    try:
        result = connectome.make_synthetic(path, shape=shape, n_subjects=nSubjects, runs=runs, seed=seed, name=DEMO_NAME, overwrite=True, affine=affine)
    finally:
        writerClass.add_subject = originalAddSubject
    connectome.set_metadata(result["path"], description=f"{DEMO_LABEL}: synthetic connectome with planted networks", dataUseTerms=DEMO_TERMS,
                            licence="CC0-1.0", preprocessing={"gsr": "unknown"}, space=space)
    return result


def _demoMain(argv):
    """``demo --out DIR [--subjects N] [--seed S]``: write the synthetic demo connectome with the job protocol."""
    import os
    import shutil
    import time

    from LesionNetworkMappingLib import jobs

    parser = jobs.JsonArgumentParser(prog="python -m LesionNetworkMapping demo", description="Write the synthetic demo connectome (SYNTHETIC: not real data).")
    jobs.add_common_arguments(parser, threads_default=1)
    parser.add_argument("--out", required=True, help="the .lnmc folder to write (replaced if it exists)")
    parser.add_argument("--subjects", type=jobs.positive_int, default=DEMO_SUBJECTS, help=f"number of subjects (default: {DEMO_SUBJECTS})")
    parser.add_argument("--seed", type=int, default=0, help="random seed (default: 0)")
    args = parser.parse_args(argv)
    cancel = jobs.CancelToken(args.cancel_file)
    jobs.emit("start", job="demo", argv=list(argv), threads=args.threads)
    jobs.emit("stage", name="subjects", index=1, total=1)
    started = time.monotonic()

    def onSubject(done, total):
        jobs.progress(done, total, started)
        cancel.raise_if_cancelled(done=done)

    # Written beside the destination and swapped in at the end, so that a stopped or failed job leaves an
    # existing demo as it was
    out = os.path.abspath(args.out)
    partial = out + ".partial"
    shutil.rmtree(partial, ignore_errors=True)
    try:
        writeDemoConnectome(partial, nSubjects=args.subjects, seed=args.seed, onSubject=onSubject)
        previous = out + ".previous"
        shutil.rmtree(previous, ignore_errors=True)
        if os.path.exists(out):
            os.replace(out, previous)
        try:
            os.replace(partial, out)
        except BaseException:
            if os.path.exists(previous) and not os.path.exists(out):
                os.replace(previous, out)
            raise
        shutil.rmtree(previous, ignore_errors=True)
    except BaseException:
        shutil.rmtree(partial, ignore_errors=True)
        raise
    jobs.emit("result", kind="connectome", path=out)
    jobs.emit("done", outputs=[out], elapsed=round(jobs.elapsed(), 3), run_id=None)


def _jobMain(argv):
    """``job <module> [arguments] [--cancel-file F]``: run a LesionNetworkMappingLib command line as a job; return the exit code."""
    import importlib
    import os
    import threading

    from LesionNetworkMappingLib import jobs

    if argv[:1] == ["demo"]:
        return jobs.run_job(_demoMain, argv[1:], job="demo", exit=False)
    if len(argv) < 2 or argv[0] != "job" or not argv[1].startswith("LesionNetworkMappingLib."):
        print("usage: python -m LesionNetworkMapping job LesionNetworkMappingLib.<module> [arguments] [--cancel-file FILE]\n"
              "       python -m LesionNetworkMapping demo --out DIR [--subjects N] [--cancel-file FILE]", file=sys.stderr)
        return jobs.EXIT_USAGE
    moduleName, arguments, cancelFile = argv[1], [], None
    remaining = iter(argv[2:])
    for argument in remaining:
        if argument == "--cancel-file":
            cancelFile = next(remaining, None)
        elif argument.startswith("--cancel-file="):
            cancelFile = argument.split("=", 1)[1]
        else:
            arguments.append(argument)
    nice = os.environ.get("SLICER_LNM_NICE", "")
    if nice.isdigit() and int(nice) > 0 and hasattr(os, "nice"):
        # Before the module (and numpy's BLAS threads) is loaded, so that every thread runs at the lower priority
        try:
            os.nice(int(nice))
        except OSError:
            pass
    target = importlib.import_module(moduleName)
    if cancelFile:

        def watchCancelFile():
            while True:
                if os.path.exists(cancelFile):
                    jobs.request_cancel("cancel file")
                    return
                threading.Event().wait(0.2)

        threading.Thread(target=watchCancelFile, name="cancel-file", daemon=True).start()
    return jobs.run_job(target.main, arguments, job=moduleName.rsplit(".", 1)[-1], exit=False)


if __name__ == "__main__":
    sys.exit(_jobMain(sys.argv[1:]))

