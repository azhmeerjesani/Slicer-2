    def onSegmentationChanged(self, node):
        if self._updatingGui:
            return
        self._populateSegments(node)
        segmentId = self.segmentSelector.currentData if self.segmentSelector.count else ""
        self._setSeed(node, segmentId)

    def onSegmentChanged(self, index):
        if self._updatingGui or index < 0:
            return
        self._setSeed(self.segmentationSelector.currentNode(), self.segmentSelector.itemData(index) or "")

    def _setSeed(self, node, segmentId):
        if self._parameterNode is None:
            return
        self.ctx.setSeed(node, segmentId)
        self._observeSeed(node)
        self.scheduleSeedUpdate()

    def _populateSegments(self, node, selectId=None):
        wasBlocked = self.segmentSelector.blockSignals(True)
        self.segmentSelector.clear()
        lesionIndex = -1
        if node is not None:
            segmentation = node.GetSegmentation()
            for index in range(segmentation.GetNumberOfSegments()):
                segmentId = segmentation.GetNthSegmentID(index)
                name = segmentation.GetSegment(segmentId).GetName()
                self.segmentSelector.addItem(name, segmentId)
                if name.lower() == "lesion" and lesionIndex < 0:
                    lesionIndex = index
        target = self.segmentSelector.findData(selectId) if selectId else -1
        if target < 0:
            target = lesionIndex if lesionIndex >= 0 else (0 if self.segmentSelector.count else -1)
        self.segmentSelector.setCurrentIndex(target)
        self.segmentSelector.blockSignals(wasBlocked)

    def _observeSeed(self, node):
        if self._observedSeed is not None:
            for event in self._seedEvents():
                self.removeObserver(self._observedSeed, event, self.onSeedModified)
        self._observedSeed = node
        if node is not None:
            for event in self._seedEvents():
                self.addObserver(node, event, self.onSeedModified)

    @staticmethod
    def _seedEvents():
        return (slicer.vtkSegmentation.SegmentAdded, slicer.vtkSegmentation.SegmentRemoved, slicer.vtkSegmentation.SegmentModified,
                slicer.vtkSegmentation.SourceRepresentationModified)

    def onSeedModified(self, caller=None, event=None):
        if caller is not None and caller is self.segmentationSelector.currentNode():
            current = self.segmentSelector.currentData if self.segmentSelector.count else None
            self._populateSegments(caller, current)
            segmentId = self.segmentSelector.currentData if self.segmentSelector.count else ""
            if self._parameterNode is not None and segmentId != (self._parameterNode.seedSegmentId or ""):
                self.ctx.setSeed(caller, segmentId)
        self.scheduleSeedUpdate()

    def scheduleSeedUpdate(self):
        """Check the seed soon; while Map is not shown only remember it (no labelmap export while drawing in Draw)."""
        if not self._entered:
            self._seedDirty = True
            return
        self.seedTimer.start()

    def updateSeed(self):
        """Check the seed against the connectome (geometry line, errors) and refresh the Compute state."""
        self.seedTimer.stop()
        self._seedDirty = False
        segNode, segmentId = self.ctx.seed() if self.ctx is not None else (None, None)
        try:
            self.seedCheck = self.logic.checkSeed(segNode, segmentId, self.bundle)
        except Exception as exc:
            logging.exception("Lesion network mapping: the seed could not be checked")
            self.seedCheck = {"ok": False, "reason": _("The lesion could not be read: {error}").format(error=exc), "kind": "error", "space": None, "volumeMl": 0.0, "qc": None}
        self._showSeed(segNode, segmentId)
        self.updateComputeState()
        self._notifyControllers("onSeedChecked", self.seedCheck)

    def _showSeed(self, segNode, segmentId):
        check = self.seedCheck or {}
        segment = segNode.GetSegmentation().GetSegment(segmentId) if segNode is not None and segmentId else None
        if segment is not None:
            r, g, b = segment.GetColor()
            self.seedSwatch.setStyleSheet(f"background-color: rgb({int(r * 255)},{int(g * 255)},{int(b * 255)}); border-radius: 2px;")
            self.seedSwatch.show()
            self.seedNameLabel.setText(f"{segment.GetName()} · {check.get('volumeMl', 0.0):.2f} mL")
        else:
            self.seedSwatch.hide()
            self.seedNameLabel.setText(_("No lesion selected"))
        space = check.get("space")
        if space:
            name, resolution = space
            self.widgets.setChipLevel(self.seedSpaceChip, "ok", f"{name}" + (f" {resolution:g} mm" if isinstance(resolution, (int, float)) else ""))
            self.seedSpaceChip.show()
        elif check.get("kind") in ("native",) or (segment is not None and check.get("kind") not in ("empty", "none") and self.bundle is None):
            self.widgets.setChipLevel(self.seedSpaceChip, "warn", _("Native space"))
            self.seedSpaceChip.show()
        else:
            self.seedSpaceChip.hide()
        qcValues = check.get("qc")
        if qcValues and self.bundle is not None:
            spacing = abs(float(self.bundle.grid.spacing[0]))
            self.seedGeometryLabel.setText(_("On connectome grid ({spacing:g} mm): {voxels:,} voxels · fractional sum {total:.1f}").format(
                spacing=spacing, voxels=int(qcValues.get("voxels_in_mask", 0)), total=float(qcValues.get("weight_total", 0.0))))
            self.seedGeometryLabel.show()
        else:
            self.seedGeometryLabel.setText("")
            self.seedGeometryLabel.setVisible(False)
        reason = check.get("reason") if not check.get("ok") and check.get("kind") not in ("none",) else ""
        self.widgets.setBannerText(self.seedErrorBanner, reason or "")
        self.seedErrorBanner.setVisible(bool(reason))
        self.normalizeLinkButton.setVisible(check.get("kind") == "native")

