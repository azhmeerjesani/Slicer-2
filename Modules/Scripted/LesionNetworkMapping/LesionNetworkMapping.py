        try:
            self._demoJob = self.logic.startDemoJob(onEvent=self._onDemoEvent, onDone=self._onDemoDone)
        except Exception as e:
            logging.exception("Lesion network mapping: the demo job could not be started")
            slicer.util.errorDisplay(_("The demo connectome could not be created."), detailedText=str(e))
            return
        self._updateDemoButton(_("Creating the demo…"))

