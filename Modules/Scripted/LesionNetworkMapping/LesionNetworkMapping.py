    def checkSeed(self, segNode, segmentId, bundle=None):
        """Check a seed against a connectome; return a dict.

        Keys: ``ok`` (bool), ``reason`` (why it cannot be mapped, or ""), ``kind`` ("", "empty", "native",
        "outside", "small"), ``space`` ((name, resolution) or None), ``volumeMl``, and with a bundle
        ``qc`` (``engine.prepare_lesion``'s voxels_in_mask, weight_total, ...).
        """
        import numpy as np

        result = {"ok": False, "reason": "", "kind": "", "space": None, "volumeMl": 0.0, "qc": None}
        if segNode is None or not segmentId or segNode.GetSegmentation().GetSegment(segmentId) is None:
            result.update(reason=_("Choose the lesion segment."), kind="none")
            return result
        data, affine = self.seedArray(segNode, segmentId)
        voxels = int(np.count_nonzero(data))
        result["volumeMl"] = voxels * abs(float(np.linalg.det(affine[:3, :3]))) / 1000.0
        if voxels == 0:
            result.update(reason=_("The lesion segment is empty: trace it in Draw first."), kind="empty")
            return result
        result["space"] = self.seedSpace(segNode, data.shape, affine)
        if bundle is None:
            result["ok"] = True
            return result
        from LesionNetworkMappingLib import engine, geometry

        connectomeSpace = geometry.detect_space((bundle.shape, bundle.affine))
        # A connectome on a non-standard grid may declare its template space (connectome.json "space": the demo)
        declaredSpace = (getattr(bundle, "metadata", None) or {}).get("space")
        templateConnectome = connectomeSpace is not None or geometry.space_family(declaredSpace) not in ("native", "unknown")
        if result["space"] is None and templateConnectome:
            result.update(reason=_("Native space: normalize to MNI first (see Normalize to MNI below). The lesion is not on a known MNI grid, so it cannot be mapped with an MNI connectome."), kind="native")
            return result
        if connectomeSpace is None:
            # A connectome on a non-standard grid (the synthetic demo, test bundles): the lesion must lie inside its grid
            gridCorners = np.array([[i, j, k, 1.0] for i in (0, bundle.shape[0] - 1) for j in (0, bundle.shape[1] - 1) for k in (0, bundle.shape[2] - 1)])
            gridBox = (bundle.affine @ gridCorners.T).T[:, :3]
            nonzero = np.argwhere(data)
            world = (affine[:3, :3] @ nonzero.T).T + affine[:3, 3]
            low, high = gridBox.min(axis=0) - 1.0, gridBox.max(axis=0) + 1.0
            if not np.all((world >= low) & (world <= high)):
                result.update(reason=_("The lesion lies outside the connectome's grid: it is not in the connectome's space."), kind="outside")
                return result
        qc = engine.prepare_lesion((data, affine), bundle)[1]
        result["qc"] = qc
        if qc.get("weight_total", 0.0) < 1.0:
            result.update(reason=_("Lesion smaller than one connectome voxel."), kind="small")
            return result
        result["ok"] = True
        return result

