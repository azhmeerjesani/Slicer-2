    @staticmethod
    def connectomeLine(bundle):
        """The metadata line of a bundle, e.g. "GSP1000 v3.0 (doi:…) · N=1000 · 18-36 y · GSR · 292,019 vox · 2 mm · 126 GB"."""
        provenance = getattr(bundle, "provenance", {}) or {}
        source = provenance.get("source") or {}
        population = provenance.get("population") or {}
        gsr = (provenance.get("preprocessing") or {}).get("gsr")
        name = bundle.name
        if source.get("version"):
            name += f" v{source['version']}"
        if source.get("doi"):
            name += f" (doi:{source['doi']})"
        parts = [name, f"N={bundle.n_subjects:,}"]
        if population.get("ageRange"):
            ages = population["ageRange"]
            parts.append(f"{ages[0]}–{ages[1]} y" if isinstance(ages, (list, tuple)) and len(ages) == 2 else f"{ages} y")  # noqa: RUF001
        if gsr is True:
            parts.append("GSR")
        elif gsr is False:
            parts.append("no GSR")
        spacing = [abs(float(value)) for value in bundle.grid.spacing]
        resolution = f"{spacing[0]:g} mm" if max(spacing) - min(spacing) < 1e-3 else " × ".join(f"{value:g}" for value in spacing) + " mm"  # noqa: RUF001
        parts += [f"{bundle.n_voxels:,} vox", resolution, _formatBytes(bundle.data_size_bytes)]
        return " · ".join(parts)

