def _settingList(key):
    value = qt.QSettings().value(key)
    if value is None or value == "":
        return []
    if isinstance(value, str):
        return [value]
    return [str(item) for item in value if item]


def _safeName(text, default="lesion"):
    """Letters, digits and dashes of ``text`` (a BIDS-style label), or ``default``."""
    name = re.sub(r"[^A-Za-z0-9-]+", "", text or "")
    return name or default


class LesionNetworkMappingLogic(ScriptedLoadableModuleLogic):
    """Computation and data handling of the Map module, usable without the GUI (tests, scripts)."""

    #: {connectome identifier: local bundle path} of the bundles opened in this session (shared by all logic instances)
    _knownConnectomes = {}

    def __init__(self):
        ScriptedLoadableModuleLogic.__init__(self)
        self._bundleCache = {}

    def getParameterNode(self):
        return LesionNetworkMappingParameterNode(super().getParameterNode())

    #
    # Connectomes
    #

    @staticmethod
    def registeredConnectomes():
        """Paths of the registered connectome bundles (``Studio/LNM/Connectomes``), in registration order."""
        paths = []
        for path in _settingList(CONNECTOMES_SETTING):
            if path not in paths:
                paths.append(path)
        return paths

    @staticmethod
    def registerConnectome(path):
        """Validate a bundle (``ConnectomeBundle.open``) and add it to the registered list; return the bundle."""
        from LesionNetworkMappingLib.connectome import ConnectomeBundle

        bundle = ConnectomeBundle.open(path)
        paths = LesionNetworkMappingLogic.registeredConnectomes()
        if bundle.path not in paths:
            paths.append(bundle.path)
            qt.QSettings().setValue(CONNECTOMES_SETTING, paths)
        return bundle

    @staticmethod
    def unregisterConnectome(path):
        """Remove a bundle from the registered list (its files are kept)."""
        paths = [item for item in LesionNetworkMappingLogic.registeredConnectomes() if os.path.normpath(item) != os.path.normpath(path)]
        qt.QSettings().setValue(CONNECTOMES_SETTING, paths)

    @staticmethod
    def connectomeIdentifier(bundle):
        """Portable identifier of a connectome bundle, saved in scenes instead of its local path (SPEC 9.7 rule 10).

        ``"<name>#<fingerprint>"``: the bundle name and the first 16 hex digits of ``export.data_sha256`` (grid,
        subjects and format of connectome.json; no data file is read), so the same bundle in another folder or on
        another computer has the same identifier.
        """
        from LesionNetworkMappingLib.export import data_sha256

        return f"{bundle.name}#{data_sha256(bundle.metadata)[:16]}"

    @staticmethod
    def connectomeIdentifierName(identifier):
        """The bundle name of a connectome identifier (the whole text for one without a fingerprint)."""
        return (identifier or "").rsplit("#", 1)[0]

    def rememberConnectome(self, bundle):
        """Remember where the bundle of this session is (``resolveConnectome``); return its identifier."""
        identifier = self.connectomeIdentifier(bundle)
        LesionNetworkMappingLogic._knownConnectomes[identifier] = bundle.path
        return identifier

    def resolveConnectome(self, identifier):
        """Local folder of the connectome with this identifier, "" if it is not on this computer.

        Looks among the bundles opened in this session and the registered bundles (the fork-only setting
        ``Studio/LNM/Connectomes``, which keeps the local paths out of the scene).
        """
        if not identifier:
            return ""
        name = self.connectomeIdentifierName(identifier)
        nameOnly = "#" not in identifier  # a legacy scene whose bundle was missing: its folder name (legacyConnectomeName)
        known = LesionNetworkMappingLogic._knownConnectomes.get(identifier)
        candidates = ([known] if known else []) + [path for path in self.registeredConnectomes() if path != known]
        for path in candidates:
            try:
                bundle = self.openBundle(path)
            except Exception:
                continue
            if nameOnly:
                if name in (bundle.name, legacyConnectomeName(bundle.path)):
                    return bundle.path
            elif bundle.name == name and self.connectomeIdentifier(bundle) == identifier:
                return bundle.path
        return ""

    def openBundle(self, path):
        """The open ``ConnectomeBundle`` of ``path`` (cached while connectome.json is unchanged)."""
        from LesionNetworkMappingLib.connectome import ConnectomeBundle

        path = os.path.abspath(path)
        manifest = os.path.join(path, "connectome.json")
        stamp = os.stat(manifest).st_mtime_ns if os.path.isfile(manifest) else None
        cached = self._bundleCache.get(path)
        if cached is not None and cached[0] == stamp:
            return cached[1]
        bundle = ConnectomeBundle.open(path)
        self._bundleCache[path] = (stamp, bundle)
        return bundle

    @staticmethod
    def demoPath():
        return os.path.join(slicer.app.cachePath, "LNM", "demo.lnmc")

    def createDemoConnectome(self, path=None, nSubjects=DEMO_SUBJECTS, register=True, shape=DEMO_SHAPE, runs=DEMO_RUNS, seed=0, affine="demo"):
        """Write the synthetic demo connectome (planted networks, ``connectome.make_synthetic``) and register it.

        The default grid covers the MNI brain with 6 mm voxels and records the space ``DEMO_SPACE``;
        ``affine=None`` gives make_synthetic's 2 mm grid around the origin (no space). Returns the ``make_synthetic`` result (path, blobs...). It is labelled
        SYNTHETIC in its name, description and data use terms. This runs on the calling thread: the "Use the demo"
        button runs ``startDemoJob()`` instead.
        """
        result = writeDemoConnectome(path or self.demoPath(), nSubjects=nSubjects, shape=shape, runs=runs, seed=seed, affine=affine)
        self._bundleCache.pop(os.path.abspath(result["path"]), None)
        if register:
            self.registerConnectome(result["path"])
        return result

    def startDemoJob(self, path=None, onEvent=None, onDone=None, nSubjects=DEMO_SUBJECTS):
        """Write the demo connectome in a job of the shared job runner (``python -m LesionNetworkMapping demo``).

        The connectome is not registered here: ``onDone(job)`` does it when ``job.succeeded()``. Return the ``jobrunner.Job``.
        """
