    def computeState(self):
        """(enabled, reason) of Map network; the reason is shown under the button (never only in a tooltip)."""
        from LesionNetworkMappingUI import jobrunner

        mode = self.seedMode()
        override = self.ctx.primaryOverride(mode) if self.ctx is not None else None
        if override is not None:
            enabledFn = override[2]
            try:
                enabled = True if enabledFn is None else bool(enabledFn())
            except Exception:
                enabled = False
            return enabled, "" if enabled else _("Not ready")
        if self.job is not None and (self.job.isRunning() or self.job.isQueued()):
            return False, _("Mapping…")
        if mode != "lesion":
            return False, _("This seed mode is not available yet.")
        if self.bundle is None:
            return False, _("Add a connectome, or use the demo, to map.")
        if not self.acceptTermsCheckBox.checked:
            return False, _("Accept the data use terms of {name} to map.").format(name=self.bundle.name)
        check = self.seedCheck
        if check is None:
            return False, _("Checking the lesion…")
        if not check.get("ok"):
            return False, check.get("reason") or _("Choose the lesion segment.")
        if not self.ctx.computeEnabled():
            return False, " ".join(self.ctx.computeDisabledReasons()) or _("Not ready")
        runner = jobrunner.instance()
        if runner.isBusy():
            return True, _("Another computation is running: this one will wait for it.")
        return True, ""

    def updateComputeState(self):
        if not hasattr(self, "computeButton"):
            return
        mode = self.seedMode()
        override = self.ctx.primaryOverride(mode)
        self.computeButton.setText(override[0] if override is not None else _("Map network"))
        enabled, reason = self.computeState()
        self.computeButton.setEnabled(enabled)
        self.computeReasonLabel.setText(reason)
        self.computeReasonLabel.setVisible(bool(reason))
        self._updatePrimaryAction()
        self._updateStatusChip()

    def onPrimary(self):
        """The primary action (the button and Ctrl+Enter in Studio): preflight checks, then Map network."""
        mode = self.seedMode()
        override = self.ctx.primaryOverride(mode)
        if override is not None:
            override[1]()
            return
        if self._seedDirty or self.seedTimer.isActive() or self.seedCheck is None:
            self.updateSeed()
        enabled, reason = self.computeState()
        if not enabled:
            self.computeReasonLabel.setText(reason)
            self.computeReasonLabel.setVisible(bool(reason))
            return
        if not self._preflight():
            return
        self.compute()

    def _preflight(self):
        """Run the beforeCompute hooks; show failures with their fix actions; return whether Compute may go on."""
        while self.preflightLayout.count():
            item = self.preflightLayout.takeAt(0)
            if item.widget() is not None:
                item.widget().deleteLater()
        failures = [(message, fix) for ok, message, fix in self.ctx.checkBeforeCompute() if not ok]
        for message, fix in failures:
            actions = [fix] if fix else []
            self.preflightLayout.addWidget(self.widgets.banner(message, actions, level="warn"))
        return not failures

    def compute(self):
        """Export the seed lesion and start the engine (non-blocking); return the job."""
        from LesionNetworkMappingLib import thresholds

        node = self._parameterNode
        segNode, segmentId = self.ctx.seed()
        segmentName = segNode.GetSegmentation().GetSegment(segmentId).GetName()
        lesionName = _safeName(self._subjectLabel() or f"{segNode.GetName()}-{segmentName}")
        runDir = self.logic.runDirectory(self.ctx, lesionName)
        lesionPath = os.path.join(runDir, "lesion", f"{lesionName}.nii.gz")
        self.logic.exportSeedLesion(segNode, segmentId, lesionPath)
        previewN = self.plannedN() if node.subjectsMode == "preview" and self.plannedN() < self.bundle.n_subjects else None
        rule = self.currentRule()
        # The shown result is kept, untouched, until the new run has a map; it comes back if the run ends without one
        self._previousRun = {"volume": node.resultVolume, "ctxVolume": self.ctx.resultVolume, "run": self.ctx.currentRun, "mapStamp": dict(self._mapStamp),
                             "state": (self.lesionName, self.runDir, self.runOutputs, self.runN, self.runPartial, self.runPreviewN, self.runDescSuffix)}
        self.lesionName, self.runDir = lesionName, runDir
        self.runOutputs, self.runN, self.runPartial = {}, None, False
        self.runPreviewN = previewN
        self.runDescSuffix = f"PreviewN{previewN}" if previewN else ""
        self._mapStamp.clear()
        self._valuesCache.clear()
        self.widgets.setBannerText(self.computeBanner, "")
        self.computeBanner.hide()
        config = {"bundlePath": self.bundle.path, "lesionPath": lesionPath, "runDir": runDir, "previewN": previewN, "previewSeed": node.previewSeed,
                  "nullRelocations": node.nullRelocations, "rule": thresholds.normalize_rule(rule)}
        self._prepareResultVolume()
        self.ctx.setCurrentRun(None)
        self.refreshResult()  # the Result card waits for the new map (no title, rule or Export of the previous run)
        try:
            self.job = self.logic.startRun(config, onEvent=self.onRunEvent, onDone=self.onRunDone, context=self.ctx)
        except Exception:
            self._restorePreviousRun()
            raise
        self.progress.setJob(self.job)
        self.progress.widget.show()
        self.updateComputeState()
        return self.job

    def _prepareResultVolume(self):
        """Set up the result volume on the connectome grid before the run (empty, with the colour table and the
        layers), so that each partial map only updates its voxels: one render per map while the engine runs.

        A new volume, so that an earlier result is never overwritten (SPEC 7.2); only the temporary volume of a
        run that never produced a map (``LNM.Computing``) is reused.
        """
        import numpy as np

        from LesionNetworkMappingLib import display

        node = self._parameterNode
        volume = node.resultVolume if node is not None else None
        bundle = self.bundle
        name = f"{self.lesionName} LNM {self.currentStatistic()} " + _("(computing…)")
        zeros = np.zeros(tuple(reversed(bundle.shape)), dtype=np.float32)
        reuse = (volume is not None and volume.GetScene() is not None and volume.GetAttribute(COMPUTING_ATTRIBUTE) == "1" and not volume.GetSaveWithScene()
                 and volume.GetImageData() is not None and tuple(volume.GetImageData().GetDimensions()) == tuple(bundle.shape))
        if not reuse:
            volume = slicer.util.addVolumeFromArray(zeros, ijkToRAS=bundle.affine, name=name, nodeClassName="vtkMRMLScalarVolumeNode")
        else:
            volume.SetName(name)
        volume.SetAttribute(display.RESULT_ATTRIBUTE, "1")
        volume.SetAttribute(COMPUTING_ATTRIBUTE, "1")
        volume.SetSaveWithScene(False)  # a temporary until the map is complete (also kept out of autosave)
        display.applyResultDisplay(volume, window=float(volume.GetAttribute(display.WINDOW_ATTRIBUTE) or 1.0), threshold=float("inf"), sign=self._sign())
        if node is not None and node.resultVolume is not volume:
            node.resultVolume = volume
        self._mapStamp.clear()
        self._showLayers(volume)

