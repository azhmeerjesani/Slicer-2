    def _showRuleControls(self, rule):
        self._updatingGui = True
        try:
            self.ruleCombo.setCurrentIndex(max(0, self.ruleCombo.findData(rule["kind"])))
            spin = self.ruleValueSpinBox
            if rule["kind"] == "fwe_bonferroni":
                spin.setPrefix("α ")  # noqa: RUF001
                spin.setSuffix("")
                spin.setDecimals(3)
                spin.setRange(0.001, 0.5)
                spin.setSingleStep(0.01)
                spin.setValue(rule["alpha"])
            elif rule["kind"] == "top_pct":
                spin.setPrefix(_("top "))
                spin.setSuffix(" %")
                spin.setDecimals(1)
                spin.setRange(0.1, 99.9)
                spin.setSingleStep(1.0)
                spin.setValue(rule["value"])
            elif rule["kind"] == "fz_abs":
                spin.setPrefix("|Fz| ≥ ")
                spin.setSuffix("")
                spin.setDecimals(3)
                spin.setRange(0.001, 5.0)
                spin.setSingleStep(0.01)
                spin.setValue(rule["value"])
            else:
                spin.setPrefix("|T| ≥ ")
                spin.setSuffix("")
                spin.setDecimals(2)
                spin.setRange(0.1, 100.0)
                spin.setSingleStep(0.5)
                spin.setValue(rule["value"])
        finally:
            self._updatingGui = False

    def onRuleKindChanged(self, index):
        from LesionNetworkMappingLib import thresholds

        kind = self.ruleCombo.itemData(index)
        rule = {"kind": kind}
        if kind == "custom_t":
            rule["reference_n"] = self.runN or self.plannedN() or None
        if kind == "top_pct":
            rule["sign"] = self._sign()
            rule["statistic"] = "T" if self.currentStatistic() == "T" else "Fz"
        self._ruleOverride = False
        self.setRule(thresholds.normalize_rule(rule))

    def onRuleValueChanged(self, value):
        if self._updatingGui:
            return
        rule = dict(self.currentRule())
        if rule["kind"] == "fwe_bonferroni":
            rule["alpha"] = float(value)
        else:
            rule["value"] = float(value)
        self.setRule(rule)

