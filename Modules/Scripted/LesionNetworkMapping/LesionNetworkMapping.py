    @staticmethod
    def readMap(path):
        """(data indexed [k, j, i] for Slicer, 4x4 IJK→RAS) of a NIfTI map (3D; a 4D map gives its first volume)."""
        import numpy as np

        from LesionNetworkMappingLib import nifti

        data, affine, _header = nifti.read_nifti(path)
        if data.ndim > 3:
            data = data.reshape(data.shape[:3] + (-1,))[..., 0]
        if data.dtype.kind == "f" and data.dtype != np.float32:
            data = data.astype(np.float32)
        return np.ascontiguousarray(np.transpose(data, (2, 1, 0))), affine

    def loadMap(self, path, name=None, volumeNode=None, saveWithScene=True, attributes=None):
        """Load a map (T/Fz/r, or a group map: uint8 binary, float percent or T) with its NIfTI affine.

        Updates ``volumeNode`` in place (``updateVolumeFromArray``, partial snapshots; one modified event)
        or adds a new scalar volume. The volume gets the node attribute ``LNM.Result`` = "1" (Draw hides
        such volumes) and the given ``attributes``.
        """
        from LesionNetworkMappingLib import display

        data, affine = self.readMap(path)
        if volumeNode is None or volumeNode.GetScene() is None:
            volumeNode = slicer.util.addVolumeFromArray(data, ijkToRAS=affine, name=name or os.path.basename(path), nodeClassName="vtkMRMLScalarVolumeNode")
            wasModifying = volumeNode.StartModify()
        else:
            wasModifying = volumeNode.StartModify()
            matrix = vtk.vtkMatrix4x4()
            for row in range(4):
                for column in range(4):
                    matrix.SetElement(row, column, float(affine[row, column]))
            current = vtk.vtkMatrix4x4()
            volumeNode.GetIJKToRASMatrix(current)
            if any(abs(current.GetElement(row, column) - matrix.GetElement(row, column)) > 1e-9 for row in range(4) for column in range(4)):
                volumeNode.SetIJKToRASMatrix(matrix)
            slicer.util.updateVolumeFromArray(volumeNode, data)
            if name:
                volumeNode.SetName(name)
        volumeNode.SetAttribute(display.RESULT_ATTRIBUTE, "1")
        for key, value in (attributes or {}).items():
            volumeNode.SetAttribute(key, str(value))
        volumeNode.SetSaveWithScene(bool(saveWithScene))
        volumeNode.EndModify(wasModifying)
        return volumeNode

