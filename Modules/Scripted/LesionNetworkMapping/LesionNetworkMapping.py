    def scheduleRefresh(self, reloadMaps=False):
        """Refresh the result on the next event loop turn (coalesced; used for engine events)."""
        self._pendingReload = self._pendingReload or reloadMaps
        self.refreshTimer.start()

    def _onRefreshTimer(self):
        if self.ctx is None or getattr(slicer.modules, "LesionNetworkMappingWidget", None) is not self:
            return
        reloadMaps, self._pendingReload = self._pendingReload, False
        self.refreshResult(reloadMaps=reloadMaps, deferred=True)

    def refreshResult(self, reloadMaps=False, peaks=None, deferred=False):
        """Show the current map: load it when needed, re-resolve the rule for its N and rewrite the colour table alphas.

        With ``deferred`` (engine events) the peak table is updated in a later event loop turn; the map and
        its colour table change in the same turn, so that the views render once per new map.
        """
        if not hasattr(self, "derivedLabel"):
            return
        node = self._parameterNode
        statistic = self.currentStatistic()
        resultVolume = node.resultVolume if node is not None else None
        hasMap = bool(self.runOutputs) and self.bundle is not None
        self._refreshGeneration += 1

        # Map: load or update the volume (never on a pure threshold change)
        mapChanged = False
        if hasMap and (reloadMaps or resultVolume is None):
            path = self.runOutputs.get(STATISTIC_KEYS[statistic])
            if path and os.path.isfile(path):
                stamp = (path, os.stat(path).st_mtime_ns, self.runN, self.runPartial)
                if reloadMaps or self._mapStamp.get("volume") != stamp or resultVolume is None:
                    saveWithScene = not self.runPartial or not (self.job is not None and self.job.isRunning())
                    saveWithScene = saveWithScene and not self.runPreviewN
                    attributes = {"LNM.Statistic": statistic, "LNM.N": self.runN, "LNM.Partial": "1" if self.runPartial else "0"}
                    newVolume = self.logic.loadMap(path, self._resultName(statistic), resultVolume, saveWithScene=saveWithScene, attributes=attributes)
                    self._mapStamp["volume"] = stamp
                    mapChanged = True
                    if newVolume.GetAttribute(COMPUTING_ATTRIBUTE) is not None:
                        newVolume.RemoveAttribute(COMPUTING_ATTRIBUTE)
                        self._revealCard("result")  # the run's first map: scroll the Result card into view
                    self._previousRun = None  # the new run has a map
                    if resultVolume is None or newVolume is not resultVolume:
                        resultVolume = newVolume
                        if node is not None:
                            node.resultVolume = newVolume
                        self._showLayers(newVolume)
                    self.ctx.setResultVolume(newVolume)
        elif hasMap and resultVolume is not None and resultVolume.GetName() != self._resultName(statistic):
            resultVolume.SetName(self._resultName(statistic))
        self._refreshRule(mapChanged, peaks, deferred)

    def _refreshRule(self, mapChanged, peaks, deferred):
        """Second step of ``refreshResult``: the rule for the current N, the colour table alphas, the peaks."""
        from LesionNetworkMappingLib import display, thresholds

        node = self._parameterNode
        rule = self.currentRule()
        statistic = self.currentStatistic()
        n = self.runN if self.runN else self.plannedN()
        resultVolume = node.resultVolume if node is not None else None
        hasMap = bool(self.runOutputs) and self.bundle is not None
        for button in (self.binarizeButton, self.resultExportButton):
            button.setEnabled(hasMap and resultVolume is not None)
        if hasMap:
            self.resultTitleLabel.setText(_("{name} · {state}").format(
                name=f"{self.lesionName} · {statistic}", state=(_("N={n} (partial)") if self.runPartial else _("N={n}")).format(n=self.runN)
                + (_(" · Preview") if self.runPreviewN else "")))
        elif resultVolume is not None and resultVolume.GetAttribute(COMPUTING_ATTRIBUTE) == "1":
            self.resultTitleLabel.setText(_("Mapping: the map appears with the first partial result."))
        else:
            self.resultTitleLabel.setText(_("No map yet: Map network computes it."))

        if not hasMap and self.bundle is not None and self._preloading and "scipy.stats" not in sys.modules and rule["kind"] in ("fwe_bonferroni", "t_convention", "custom_t"):
            # The planned threshold waits for the background import of scipy (never a long freeze on entering Map)
            self.derivedLabel.setText(_("Resolving the threshold rule…"))
            self.emptyResultLabel.hide()
            self.peaksTable.hide()
            return

        # Rule: re-resolved for the current N on every update
        self.resolved = None
        banner, notes, empty = "", [], ""
        if self.bundle is not None and n:
            ruleStatistic = self._ruleStatistic(rule)
            values = self._mapValues(ruleStatistic) if hasMap else None
            note = "partial" if self.runPartial else ("preview" if (self.runPreviewN if hasMap else node is not None and node.subjectsMode == "preview") else None)
            try:
                self.resolved = self.logic.resolveRule(rule, n, self.bundle, values=values, note=note)
            except ValueError as exc:
                self.derivedLabel.setText(str(exc))
            if self.resolved is not None:
                fraction = self.resolved.fraction
                line = thresholds.describe(self.resolved, fraction)
                if not hasMap:
                    line = _("Planned: {line}").format(line=line)
                self.derivedLabel.setText(line)
                banner = self.resolved.banner or ""
                if not self.resolved.allowed and not banner:
                    banner = _("This rule is not applied to this map.")
                notes = list(self.resolved.notes)
        else:
            self.derivedLabel.setText(_("Choose a connectome to resolve the threshold rule."))
        self.widgets.setBannerText(self.ruleBanner, banner)
        self.ruleBanner.setVisible(bool(banner))
        self.ruleNotesLabel.setText(" ".join(notes))
        self.ruleNotesLabel.setVisible(bool(notes))

        # Display: only the colour table alphas change
        self.lastPassing = None
        if hasMap and resultVolume is not None and self.resolved is not None:
            sign = self._sign()
            ruleStatistic = self._ruleStatistic(rule)
            applied = self.resolved.allowed or rule.get("override")
            if statistic == "r" or statistic != ruleStatistic:
                window = self._displayWindow(resultVolume, mapChanged)
                threshold = window / 64.0  # near-zero values hidden; the rule applies to another statistic
                display.applyResultDisplay(resultVolume, window=window, threshold=threshold, sign=sign)
                empty = _("The {statistic} map is shown unthresholded; the rule applies to the {rule} map.").format(statistic=statistic, rule=ruleStatistic)
            elif not applied or not math.isfinite(self.resolved.value):
                window = self._displayWindow(resultVolume, mapChanged)
                display.applyResultDisplay(resultVolume, window=window, threshold=window * 2.0 + 1.0, sign=sign)
                empty = _("Nothing is shown: the rule is not applied to this map. Choose Switch to FWE or Keep.")
            else:
                window = self._displayWindow(resultVolume, mapChanged)
                _window, passing = display.applyTwoSidedThreshold(resultVolume, self.resolved.value, window=window, sign=sign)
                self.lastPassing = passing
                if passing == 0:
                    quantity = {"both": f"|{ruleStatistic}|", "pos": ruleStatistic, "neg": f"−{ruleStatistic}"}[sign]  # noqa: RUF001
                    advice = _("switch to the Fz rule or use a larger connectome") if ruleStatistic == "T" else _("lower the threshold")
                    empty = _("0 voxels pass {quantity} ≥ {value:.2f} at N={n}: {advice}.").format(quantity=quantity, value=self.resolved.value, n=n, advice=advice)
        self.emptyResultLabel.setText(empty)
        self.emptyResultLabel.setVisible(bool(empty))
        if hasMap and (mapChanged or peaks):
            if deferred:
                generation = self._refreshGeneration
                qt.QTimer.singleShot(DEFERRED_STEP_MS, lambda: generation == self._refreshGeneration and self._updatePeaks(statistic))
            else:
                self._updatePeaks(statistic)
        elif not hasMap:
            self.peaksTable.hide()
        self._updateStatusChip()

