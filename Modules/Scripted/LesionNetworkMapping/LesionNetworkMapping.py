    def exportRun(self, runDir, dest, rule=None, resolved=None, partial=False):
        """Export a run folder (maps, one sidecar per lesion, provenance.json, methods.md, reproduce.sh) into ``dest``.

        Like ``export.export_run``, with the resolved threshold of the display (a top-x% rule needs the map values).
        """
        from LesionNetworkMappingLib import export

        runJson = os.path.join(runDir, "run.json")
        if not os.path.isfile(runJson):
            raise FileNotFoundError(f"Run record not found: {runJson}")
        with open(runJson, encoding="utf-8") as f:
            runMeta = json.load(f)
        if runMeta.get("status") != "done":
            if not (partial and runMeta.get("status") == "running" and runMeta.get("snapshot_n") and runMeta.get("maps")):
                raise ValueError(f"The run in {runDir} did not finish (status {runMeta.get('status')!r})")
            runMeta.update({"n": runMeta["snapshot_n"], "cancelled": True, "subject_ids_sha256": None})
        qa = {}
        qaPath = runMeta.get("qa_json") or os.path.join(runDir, "qa.json")
        if runMeta.get("status") == "done" and os.path.isfile(qaPath):
            with open(qaPath, encoding="utf-8") as f:
                qa = json.load(f).get("lesions") or {}
        names = [entry["name"] for entry in runMeta["lesions"]]
        return export.write_run(dest, runMeta["maps"], names, runMeta["bundle"], rule=rule, resolved=resolved, qa=qa, run_meta=runMeta, software=self.software())

