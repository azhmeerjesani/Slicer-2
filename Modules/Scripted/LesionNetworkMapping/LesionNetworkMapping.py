class _FitHeightFilter(qt.QObject):
    """Keeps the minimum height of the module widget at the height its word-wrapped labels need.

    The module panel's scroll area sizes its widget from ``minimumSizeHint()``, which ignores
    height-for-width (wrapped labels); without this the cards would be squeezed below their size.
    """

    def __init__(self, widget):
        qt.QObject.__init__(self, widget)
        self.widget = widget
        self.timer = qt.QTimer(self)
        self.timer.setSingleShot(True)
        self.timer.setInterval(0)
        self.timer.connect("timeout()", self.fit)
        widget.installEventFilter(self)

    def eventFilter(self, obj, event):
        if event.type() in (qt.QEvent.LayoutRequest, qt.QEvent.Resize):
            self.timer.start()
        return False

    def fit(self):
        layout = self.widget.layout()
        if layout is None or not layout.hasHeightForWidth():
            return
        height = layout.totalHeightForWidth(self.widget.width)
        if height > 0 and height != self.widget.minimumHeight:
            self.widget.setMinimumHeight(height)


